const toIndicDigits = (text, lang) => {
  if (typeof text !== 'string') {
    if (typeof text === 'number') text = String(text);
    else return text;
  }
  if (lang !== 'gu' && lang !== 'hi') return text;
  const map = DIGIT_MAPS[lang];
  return text.replace(/[0-9]/g, d => map[d] || d);
};

const recursivelyLocalizeDigits = (val, lang) => {
  if (typeof val === 'string') return toIndicDigits(val, lang);
  if (Array.isArray(val)) return val.map(item => recursivelyLocalizeDigits(item, lang));
  if (val !== null && typeof val === 'object') {
    const res = {};
    for (const k of Object.keys(val)) {
      res[k] = recursivelyLocalizeDigits(val[k], lang);
    }
    return res;
  }
  return val;
};

