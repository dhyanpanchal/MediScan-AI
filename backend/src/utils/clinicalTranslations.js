// Canonical matcher helper
const detectCanonicalId = (medName = '', genericName = '', activeIng = '', ocrText = '') => {
  const combined = `${medName} ${genericName} ${activeIng} ${ocrText}`.toLowerCase();
  if (/acenext|aceclofenac.*paracetamol|zerodol[- ]?p|hifenac[- ]?p/i.test(combined)) return 'acenext_p';
  if (/montypen|montek[- ]?lc|montair[- ]?lc|montelukast.*levocetirizine/i.test(combined)) return 'montypen_lc';
  if (/pantoprazole.*domperidone|pan[- ]?d|pantocid[- ]?d/i.test(combined)) return 'pan_d';
  if (/pantoprazole|pantocid|pan[- ]?40|protonix/i.test(combined)) return 'pantoprazole_40';
  if (/augmentin|clavam|moxikind[- ]?cv|amoxicillin.*clavulan/i.test(combined)) return 'amoxicillin_clavulanate';
  if (/combiflam|flexon|ibuprofen.*paracetamol/i.test(combined)) return 'combiflam';
  if (/dolo[- ]?650|calpol|crocin|paracetamol|tylenol|acetaminophen/i.test(combined)) return 'paracetamol';
  if (/glucophage|glyciphage|metformin|biguanide/i.test(combined)) return 'metformin';
  if (/asthalin|ventolin|salbutamol|albuterol/i.test(combined)) return 'salbutamol_inhaler';
  if (/tenovate|clop[- ]?g|dermovate|clobetasol/i.test(combined)) return 'clobetasol_cream';
  if (/vigamox|moxicip|moxiflox/i.test(combined)) return 'moxifloxacin_drops';
  if (/monocef|rocephin|oframax|ceftriaxone/i.test(combined)) return 'ceftriaxone_injection';
  return null;
};

