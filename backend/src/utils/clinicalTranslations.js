const translateTextWithPhrases = (text, lang) => {
  if (typeof text !== 'string' || !text) return text;
  if (lang !== 'gu' && lang !== 'hi') return text;
  let translated = text;
  const dict = PHRASE_DICTIONARY[lang] || [];
  for (const item of dict) {
    translated = translated.replace(item.regex, item.rep);
  }
  return toIndicDigits(translated, lang);
};

/**
 * Main translation function for any medicine payload.
 * Fully translates every field and localizes all digits.
 * @param {object} data
 * @param {string} lang ('en', 'hi', 'gu')
 * @returns {object} Fully translated medicine object
 */
function translateMedicinePayload(data, lang = 'en') {
  if (!data) return data;
  if (lang === 'en') {
    if (data._originalEnglish) {
      const restored = JSON.parse(JSON.stringify(data._originalEnglish));
      restored._originalEnglish = data._originalEnglish;
      restored._currentLang = 'en';
      return restored;
    }
    return data;
  }

  if (lang !== 'gu' && lang !== 'hi') return data;

  const originalEnglish = data._originalEnglish || JSON.parse(JSON.stringify(data));
  const translated = JSON.parse(JSON.stringify(data));
  translated._originalEnglish = originalEnglish;
  translated._currentLang = lang;

  // 1. Detect if this is one of our verified canonical monographs
  const canonicalId = detectCanonicalId(
    originalEnglish.medicineName || data.medicineName,
    originalEnglish.genericName || data.genericName,
    originalEnglish.activeIngredients || data.activeIngredients,
    originalEnglish.rawOcrText || data.rawOcrText || ''
  );

  if (canonicalId && CANONICAL_TRANSLATIONS[canonicalId] && CANONICAL_TRANSLATIONS[canonicalId][lang]) {
    const monoTrans = CANONICAL_TRANSLATIONS[canonicalId][lang];

    // Merge translated fields
    translated.medicineName = monoTrans.medicineName || translated.medicineName;
    translated.genericName = monoTrans.genericName || translated.genericName;
    translated.activeIngredients = monoTrans.activeIngredients || translated.activeIngredients;
    translated.category = monoTrans.category || translated.category;
    translated.dosageForm = monoTrans.dosageForm || translated.dosageForm;
    translated.route = monoTrans.route || translated.route;
    translated.manufacturer = monoTrans.manufacturer || translated.manufacturer;
    translated.combinationRationale = monoTrans.combinationRationale || translated.combinationRationale;
    translated.clinicalUses = monoTrans.clinicalUses || translated.clinicalUses;
    translated.purposeAndUses = monoTrans.purposeAndUses || translated.purposeAndUses;
    translated.dosage = monoTrans.dosage || translated.dosage;
    translated.dosageReference = monoTrans.dosageReference || translated.dosageReference;
    translated.usageInstructions = monoTrans.usageInstructions || translated.usageInstructions;
    translated.sideEffects = monoTrans.sideEffects || translated.sideEffects;
    translated.warnings = monoTrans.warnings || translated.warnings;
    translated.precautions = monoTrans.precautions || translated.precautions;
    translated.storage = monoTrans.storage || translated.storage;
    translated.missedDose = monoTrans.missedDose || translated.missedDose;

    if (monoTrans.activeIngredientsList) {
      translated.activeIngredientsList = JSON.parse(JSON.stringify(monoTrans.activeIngredientsList));
    }

    if (monoTrans.overview) {
      translated.overview = { ...(translated.overview || {}), ...monoTrans.overview };
    }
    if (monoTrans.dosageAndUsage) {
      translated.dosageAndUsage = { ...(translated.dosageAndUsage || {}), ...monoTrans.dosageAndUsage };
    }
    if (monoTrans.ageSpecificInfo) {
      translated.ageSpecificInfo = monoTrans.ageSpecificInfo;
    }
    if (monoTrans.interactions) {
      translated.interactions = monoTrans.interactions;
    }
  } else {
    // 2. Dynamic Fallback: apply universal phrase dictionary to all fields
    if (translated.medicineName) translated.medicineName = translateTextWithPhrases(translated.medicineName, lang);
    if (translated.genericName) translated.genericName = translateTextWithPhrases(translated.genericName, lang);
    if (translated.activeIngredients) translated.activeIngredients = translateTextWithPhrases(translated.activeIngredients, lang);
    if (translated.category) translated.category = translateTextWithPhrases(translated.category, lang);
    if (translated.dosageForm) translated.dosageForm = translateTextWithPhrases(translated.dosageForm, lang);
    if (translated.route) translated.route = translateTextWithPhrases(translated.route, lang);
    if (translated.manufacturer) translated.manufacturer = translateTextWithPhrases(translated.manufacturer, lang);
    if (translated.purposeAndUses) translated.purposeAndUses = translateTextWithPhrases(translated.purposeAndUses, lang);
    if (translated.dosage) translated.dosage = translateTextWithPhrases(translated.dosage, lang);
    if (translated.dosageReference) translated.dosageReference = translateTextWithPhrases(translated.dosageReference, lang);
    if (translated.combinationRationale) translated.combinationRationale = translateTextWithPhrases(translated.combinationRationale, lang);
    if (translated.storage) translated.storage = translateTextWithPhrases(translated.storage, lang);
    if (translated.missedDose) translated.missedDose = translateTextWithPhrases(translated.missedDose, lang);
    if (translated.usageInstructions) translated.usageInstructions = translateTextWithPhrases(translated.usageInstructions, lang);

    if (Array.isArray(translated.clinicalUses)) {
      translated.clinicalUses = translated.clinicalUses.map(u => translateTextWithPhrases(u, lang));
    }
    if (Array.isArray(translated.warnings)) {
      translated.warnings = translated.warnings.map(w => translateTextWithPhrases(w, lang));
    } else if (typeof translated.warnings === 'string') {
      translated.warnings = translateTextWithPhrases(translated.warnings, lang);
    }
    if (Array.isArray(translated.precautions)) {
      translated.precautions = translated.precautions.map(p => translateTextWithPhrases(p, lang));
    } else if (typeof translated.precautions === 'string') {
      translated.precautions = translateTextWithPhrases(translated.precautions, lang);
    }
    if (translated.sideEffects) {
      if (typeof translated.sideEffects === 'string') {
        translated.sideEffects = translateTextWithPhrases(translated.sideEffects, lang);
      } else if (typeof translated.sideEffects === 'object') {
        if (Array.isArray(translated.sideEffects.common)) {
          translated.sideEffects.common = translated.sideEffects.common.map(s => translateTextWithPhrases(s, lang));
        }
        if (Array.isArray(translated.sideEffects.serious)) {
          translated.sideEffects.serious = translated.sideEffects.serious.map(s => translateTextWithPhrases(s, lang));
        }
      }
    }
    if (Array.isArray(translated.activeIngredientsList)) {
      translated.activeIngredientsList = translated.activeIngredientsList.map(item => ({
        name: translateTextWithPhrases(item.name, lang),
        strength: toIndicDigits(item.strength, lang),
        class: translateTextWithPhrases(item.class, lang),
        mechanism: translateTextWithPhrases(item.mechanism, lang)
      }));
    }
    if (translated.overview) {
      if (translated.overview.primaryUse) translated.overview.primaryUse = translateTextWithPhrases(translated.overview.primaryUse, lang);
      if (translated.overview.drugClass) translated.overview.drugClass = translateTextWithPhrases(translated.overview.drugClass, lang);
    }
    if (translated.dosageAndUsage) {
      if (translated.dosageAndUsage.standardDose) translated.dosageAndUsage.standardDose = translateTextWithPhrases(translated.dosageAndUsage.standardDose, lang);
      if (translated.dosageAndUsage.frequency) translated.dosageAndUsage.frequency = translateTextWithPhrases(translated.dosageAndUsage.frequency, lang);
      if (translated.dosageAndUsage.duration) translated.dosageAndUsage.duration = translateTextWithPhrases(translated.dosageAndUsage.duration, lang);
      if (translated.dosageAndUsage.howToTake) translated.dosageAndUsage.howToTake = translateTextWithPhrases(translated.dosageAndUsage.howToTake, lang);
    }
  }

  // 3. Final recursive Indic digits pass across all text
  const localized = recursivelyLocalizeDigits(translated, lang);
  localized._originalEnglish = originalEnglish; // Preserve pristine original English without Indic digits
  return localized;
}

